// muszę zrobić/kupić"). Napisany od zera jako natywny Kotlin, wpięty przez ten config-plugin —
// TEN SAM wzorzec co withBankNotificationListener.js/withNativeCrashCatcher.js (kod prosto do
// wygenerowanego projektu Androida, zero zewnętrznej zależności typu react-native-android-
// widget). Świadomy wybór: ten projekt już RAZ trafił na build-breaking problem ze stale'ym
// natywnym pakietem (namespace/AGP-8 na SDK 54, patrz komentarz w withBankNotificationListener.
// js) i od tego czasu woli trzymać proste, dobrze udokumentowane natywne API (tu:
// AppWidgetProvider/RemoteViews, stabilne od lat) pod pełną kontrolą zamiast ryzykować kolejną
// niezależną bibliotekę.
//
// Przepływ: JS (widgetSync.ts) pisze JSON snapshot do filesDir (ten sam katalog co
// bankNotificationDrain.ts) i woła natywny most `TasksWidgetModule.requestUpdate()`.
// `TasksWidgetProvider.updateAll()` czyta ten plik i renderuje do 6 stałych slotów w
// RemoteViews (RemoteViews nie wspiera list/scrolla bez RemoteViewsService — 6 slotów to
// świadomy, prostszy odpowiednik "top 5-6 zadań" z widgetSync.ts). Tap w widget → deep link
// `sapp://tasks` (schemat już zarejestrowany w app.json).
