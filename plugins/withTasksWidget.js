function withSources(config) {
  return withDangerousMod(config, ['android', async (cfg) => {
    const pkg = (cfg.android && cfg.android.package) || 'com.sokki.sapp';
    const javaDir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'java', ...pkg.split('.'));
    fs.mkdirSync(javaDir, { recursive: true });
    fs.writeFileSync(path.join(javaDir, `${PROVIDER_CLASS}.kt`), providerKotlin(pkg), 'utf8');
    fs.writeFileSync(path.join(javaDir, `${MODULE_CLASS}.kt`), moduleKotlin(pkg), 'utf8');
    fs.writeFileSync(path.join(javaDir, `${PACKAGE_CLASS}.kt`), packageKotlin(pkg), 'utf8');
    fs.writeFileSync(path.join(javaDir, `${CONFIG_CLASS}.kt`), configActivityKotlin(pkg), 'utf8');

    const resDir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res');
    const layoutDir = path.join(resDir, 'layout');
    const drawableDir = path.join(resDir, 'drawable');
    const xmlDir = path.join(resDir, 'xml');
    fs.mkdirSync(layoutDir, { recursive: true });
    fs.mkdirSync(drawableDir, { recursive: true });
    fs.mkdirSync(xmlDir, { recursive: true });
    fs.writeFileSync(path.join(layoutDir, 'tasks_widget.xml'), widgetLayoutXml(), 'utf8');
    fs.writeFileSync(path.join(layoutDir, 'tasks_widget_config.xml'), widgetConfigXml(), 'utf8');
    fs.writeFileSync(path.join(drawableDir, 'widget_bg.xml'), widgetBgXml(), 'utf8');
    fs.writeFileSync(path.join(drawableDir, 'widget_dot_circle.xml'), widgetDotXml(), 'utf8');
    fs.writeFileSync(path.join(xmlDir, 'tasks_widget_info.xml'), widgetInfoXml(), 'utf8');
    return cfg;
  }]);
}

function withManifest(config) {
  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    if (!Array.isArray(app.receiver)) app.receiver = [];
    const receiverName = `.${PROVIDER_CLASS}`;
    if (!app.receiver.some((r) => r.$ && r.$['android:name'] === receiverName)) {
      app.receiver.push({
        $: { 'android:name': receiverName, 'android:exported': 'false' },
        'intent-filter': [
          { action: [{ $: { 'android:name': 'android.appwidget.action.APPWIDGET_UPDATE' } }] },
        ],
        'meta-data': [
          { $: { 'android:name': 'android.appwidget.provider', 'android:resource': '@xml/tasks_widget_info' } },
        ],
      });
    }

    if (!Array.isArray(app.activity)) app.activity = [];
    const configName = `.${CONFIG_CLASS}`;
    if (!app.activity.some((a) => a.$ && a.$['android:name'] === configName)) {
      app.activity.push({
        $: { 'android:name': configName, 'android:exported': 'true', 'android:theme': '@android:style/Theme.DeviceDefault.Dialog.NoActionBar' },
        'intent-filter': [
          { action: [{ $: { 'android:name': 'android.appwidget.action.APPWIDGET_CONFIGURE' } }] },
        ],
      });
    }
    return cfg;
  });
}

// Rejestruje TasksWidgetPackage w getPackages() — oficjalna technika Expo (mergeContents z
// markerem, idempotentna między prebuildami) zaczepiona o standardowy podpowiadający komentarz
// który Expo zawsze generuje w MainApplication.kt.
function withPackageRegistration(config) {
  return withMainApplication(config, (cfg) => {
    cfg.modResults.contents = mergeContents({
      tag: 'sapp-tasks-widget-package',
      src: cfg.modResults.contents,
      // SDK 54 generuje `PackageList(this).packages.apply { // add(MyReactNativePackage()) }`
      // (zweryfikowane realnym `expo prebuild` — NIE starszy wzorzec `packages.add(new ...)`,
      // który jest tylko w e2e fixture innego pakietu, nie w rzeczywistym szablonie tego SDK).
      // `this` wewnątrz `.apply{}` to sama lista, więc wystarczy `add(...)` bez prefiksu.
      newSrc: `              add(${PACKAGE_CLASS}())`,
      anchor: /\/\/\s*add\(MyReactNativePackage\(\)\)/,
      offset: 1,
      comment: '              //',
    }).contents;
    return cfg;
  });
}

module.exports = function withTasksWidget(config) {
  config = withSources(config);
  config = withManifest(config);
  config = withPackageRegistration(config);
  return config;
};
